"""Generates the iOS App Intents (Siri) sources from the effects' names
in the ARB files: ios/Runner/LumiFXIntents.swift, Localizable.xcstrings
and AppShortcuts.xcstrings. Run from the repository root after adding or
renaming a built-in effect:

    python3 tool/gen_ios_intents.py

(test/ios_intents_test.dart fails while the Swift file is out of date.)
"""
import json
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
english = json.loads((root / 'lib/l10n/app_en.arb').read_text())
effects = []
for key, name in english.items():
    match = re.fullmatch(r'effectName([A-Z][A-Za-z]*)', key)
    if match:
        words = re.findall(r'[A-Z][a-z]*', match[1])
        effects.append(('_'.join(w.lower() for w in words), name))

LANGS = {'it': 'it', 'de': 'de', 'fr': 'fr', 'es': 'es', 'nl': 'nl', 'pt': 'pt-BR', 'ja': 'ja'}
arbs = {lang: json.loads((root / f'lib/l10n/app_{lang}.arb').read_text()) for lang in ['en', *LANGS]}


def pascal(effect_id):
    return ''.join(p[:1].upper() + p[1:] for p in effect_id.split('_'))


def camel(effect_id):
    p = pascal(effect_id)
    return p[:1].lower() + p[1:]


def unit(value):
    return {'stringUnit': {'state': 'translated', 'value': value}}


# --- Swift -----------------------------------------------------------------
cases = '\n'.join(f'  case {camel(i)} = "{i}"' for i, _ in effects)
reps = '\n'.join(f'    .{camel(i)}: "{n}",' for i, n in effects)
swift = f'''// Generated by tool/gen_ios_intents.py from the effects' names; run it
// again, rather than editing this file, when effects change.
import AppIntents
import UIKit

/// The built-in effects Siri can play: "Play Fireplace in LumiFX".
@available(iOS 16.0, *)
enum LumiFXEffect: String, AppEnum {{
{cases}

  static var typeDisplayRepresentation: TypeDisplayRepresentation = "Effect"

  static var caseDisplayRepresentations: [LumiFXEffect: DisplayRepresentation] = [
{reps}
  ]
}}

/// Opens one of LumiFX's own links, which the app carries out as it does
/// for a link from Shortcuts or a widget (lib/src/features/links).
@MainActor
private func openLumiFX(_ path: String) async {{
  guard let url = URL(string: "lumifx://app/\\(path)") else {{ return }}
  _ = await UIApplication.shared.open(url)
}}

@available(iOS 16.0, *)
struct PlayEffectIntent: AppIntent {{
  static var title: LocalizedStringResource = "Play an effect"
  static var openAppWhenRun = true

  @Parameter(title: "Effect")
  var effect: LumiFXEffect

  @MainActor
  func perform() async throws -> some IntentResult {{
    await openLumiFX("play/\\(effect.rawValue)")
    return .result()
  }}
}}

@available(iOS 16.0, *)
struct StartBedtimeIntent: AppIntent {{
  static var title: LocalizedStringResource = "Start bedtime"
  static var openAppWhenRun = true

  @MainActor
  func perform() async throws -> some IntentResult {{
    await openLumiFX("bedtime")
    return .result()
  }}
}}

@available(iOS 16.0, *)
struct StopEffectIntent: AppIntent {{
  static var title: LocalizedStringResource = "Stop the effect"
  static var openAppWhenRun = true

  @MainActor
  func perform() async throws -> some IntentResult {{
    await openLumiFX("stop")
    return .result()
  }}
}}

/// The phrases Siri knows without any setup (translated in
/// AppShortcuts.xcstrings).
@available(iOS 16.0, *)
struct LumiFXShortcuts: AppShortcutsProvider {{
  static var appShortcuts: [AppShortcut] {{
    AppShortcut(
      intent: PlayEffectIntent(),
      phrases: [
        "Play \\(\\.$effect) in \\(.applicationName)",
        "Start \\(\\.$effect) with \\(.applicationName)",
      ],
      shortTitle: "Play an effect",
      systemImageName: "sparkles"
    )
    AppShortcut(
      intent: StartBedtimeIntent(),
      phrases: [
        "Start bedtime in \\(.applicationName)",
        "\\(.applicationName) bedtime",
      ],
      shortTitle: "Bedtime",
      systemImageName: "moon.stars"
    )
    AppShortcut(
      intent: StopEffectIntent(),
      phrases: [
        "Stop \\(.applicationName)",
        "Stop the effect in \\(.applicationName)",
      ],
      shortTitle: "Stop",
      systemImageName: "stop.circle"
    )
  }}
}}
'''
(root / 'ios/Runner/LumiFXIntents.swift').write_text(swift)

# --- Localizable.xcstrings: effect names and intent titles ----------------
titles = {
    'Effect': {'it': 'Effetto', 'de': 'Effekt', 'fr': 'Effet', 'es': 'Efecto', 'nl': 'Effect', 'pt': 'Efeito', 'ja': '効果'},
    'Play an effect': {'it': 'Avvia un effetto', 'de': 'Einen Effekt abspielen', 'fr': 'Lancer un effet', 'es': 'Reproducir un efecto', 'nl': 'Een effect afspelen', 'pt': 'Reproduzir um efeito', 'ja': '効果を再生'},
    'Start bedtime': {lang: arbs[lang]['startBedtime'] for lang in LANGS},
    'Bedtime': {lang: arbs[lang]['bedtime'] for lang in LANGS},
    'Stop the effect': {lang: arbs[lang]['buttonActionStop'] for lang in LANGS},
    'Stop': {lang: arbs[lang]['stop'] for lang in LANGS},
}
strings = {}
for key, values in titles.items():
    strings[key] = {'localizations': {LANGS[l]: unit(v) for l, v in values.items()}}
for effect_id, name in effects:
    key = f'effectName{pascal(effect_id)}'
    if key not in arbs['en']:
        sys.exit(f'no ARB name for {effect_id}')
    strings[name] = {'localizations': {LANGS[l]: unit(arbs[l][key]) for l in LANGS}}
catalog = {'sourceLanguage': 'en', 'strings': dict(sorted(strings.items())), 'version': '1.0'}
(root / 'ios/Runner/Localizable.xcstrings').write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + '\n')

# --- AppShortcuts.xcstrings: the phrases ---------------------------------
E, A = '${effect}', '${applicationName}'
phrases = {
    f'Play {E} in {A}': {'it': f'Avvia {E} con {A}', 'de': f'Spiele {E} mit {A}', 'fr': f'Lance {E} avec {A}', 'es': f'Pon {E} en {A}', 'nl': f'Speel {E} af met {A}', 'pt': f'Toque {E} no {A}', 'ja': f'{A}で{E}を再生'},
    f'Start {E} with {A}': {'it': f'Metti {E} su {A}', 'de': f'Starte {E} in {A}', 'fr': f'Joue {E} dans {A}', 'es': f'Inicia {E} con {A}', 'nl': f'Start {E} in {A}', 'pt': f'Inicie {E} com o {A}', 'ja': f'{A}で{E}をつけて'},
    f'Start bedtime in {A}': {'it': f'Avvia la nanna con {A}', 'de': f'Starte Schlafenszeit mit {A}', 'fr': f"Lance l'heure du dodo avec {A}", 'es': f'Empieza la hora de dormir con {A}', 'nl': f'Start bedtijd met {A}', 'pt': f'Comece a hora de dormir no {A}', 'ja': f'{A}でおやすみモード'},
    f'{A} bedtime': {'it': f'Nanna con {A}', 'de': f'{A} Schlafenszeit', 'fr': f'Dodo avec {A}', 'es': f'Hora de dormir con {A}', 'nl': f'{A} bedtijd', 'pt': f'Hora de dormir no {A}', 'ja': f'{A}でおやすみ'},
    f'Stop {A}': {'it': f'Ferma {A}', 'de': f'Stoppe {A}', 'fr': f'Arrête {A}', 'es': f'Detén {A}', 'nl': f'Stop {A}', 'pt': f'Pare o {A}', 'ja': f'{A}を止めて'},
    f'Stop the effect in {A}': {'it': f"Ferma l'effetto di {A}", 'de': f'Stoppe den Effekt in {A}', 'fr': f"Arrête l'effet de {A}", 'es': f'Para el efecto de {A}', 'nl': f'Stop het effect in {A}', 'pt': f'Pare o efeito do {A}', 'ja': f'{A}の効果を止めて'},
}
shortcuts = {
    'sourceLanguage': 'en',
    'strings': {k: {'localizations': {LANGS[l]: unit(v) for l, v in vs.items()}} for k, vs in phrases.items()},
    'version': '1.0',
}
(root / 'ios/Runner/AppShortcuts.xcstrings').write_text(json.dumps(shortcuts, ensure_ascii=False, indent=2) + '\n')
print('generated', len(effects), 'effects')
